export function emptySumup(now = new Date()): Database["sumup"] {
  const start = new Date(now);
  start.setHours(0, 0, 0, 0);
  return {
    locationMappings: [],
    productMappings: [],
    pending: [],
    syncFrom: start.toISOString(),
    lastSyncAt: null,
    lastSummary: "",
    lastError: null,
    channels: [...DEFAULT_SUMUP_CHANNELS],
  };
}

export function createSeed(now = new Date()): Database {
  return {
    products: seedProducts,
    orders: [],
    logs: [],
    content: seedContent,
    sumup: emptySumup(now),
  };
}
